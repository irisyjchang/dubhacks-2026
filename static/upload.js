function togglePlay() {
  if (!stage.src) {
    showScreen('home');
    return;
  }
  if (stage.paused) {
    stage.muted = false;
    stage.play().catch(() => {
      stage.muted = true;
      stage.play().catch(() => {});
    });
  } else {
    stage.pause();
  }
}

