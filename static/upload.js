stage.addEventListener('timeupdate', () => {
  if (colorSamples.length < 10 && stage.readyState >= 2 && stage.currentTime > 0.15 && stage.currentTime - lastColorAt > 0.2) {
    lastColorAt = stage.currentTime;
    applyAtmosphere(stage);
  }
  if (!scrubbing && Number.isFinite(stage.duration) && stage.duration > 0) {
    scrub.value = String(Math.round((stage.currentTime / stage.duration) * 1000));
  }
  clock.textContent = fmt(stage.currentTime);
  if (coaching.cues.length) showCue(stage.currentTime);
});

scrub.addEventListener('input', () => {
  if (!Number.isFinite(stage.duration) || stage.duration <= 0) return;
  scrubbing = true;
  stage.currentTime = (Number(scrub.value) / 1000) * stage.duration;
  clock.textContent = fmt(stage.currentTime);
  if (coaching.cues.length) showCue(stage.currentTime);
});

scrub.addEventListener('change', () => {
  scrubbing = false;
});

function showCue(time) {
  const current = coaching.cues.find((item) => time >= item.start && time < item.end) || coaching.cues[coaching.cues.length - 1];
  if (!current) return;
  cueTime.textContent = `${fmt(current.start)} – ${fmt(current.end)}`;
  cue.textContent = current.cue || firstSentence(current.observation || current.advice || '');
  const detail = current.cue ? (current.observation || current.advice) : (current.advice || '');
  cueDetail.textContent = detail && detail !== cue.textContent ? detail : '';
}

function pushMessage(role, text) {
  const item = document.createElement('div');
  item.className = `msg ${role}`;
  const who = document.createElement('div');
  who.className = 'who';
  who.textContent = role === 'coach' ? 'Coach' : 'You';
  const body = document.createElement('p');
  body.textContent = text;
  item.append(who, body);
  thread.append(item);
}

